import type { UnitCode } from "../../domain/units";

/**
 * The starter catalogue.
 *
 * `stockUnit` is how you count this thing at home. `gramsPer` bridges units a
 * recipe might use ("1 onion", "1 cup") into that stock unit. `shelfLifeDays`
 * drives the suggested best-before date; null means "keeps, don't date it".
 */

export type Category =
  | "produce"
  | "dairy"
  | "meat"
  | "fish"
  | "bakery"
  | "dry"
  | "frozen"
  | "tins"
  | "drinks"
  | "other";

